// A6 (swap-save-stamps 2026-10-01): a partial in-place write into a remote
// file that was never fully fetched. Before the fix the write made the file
// local as a whole, reads served the pre-allocated cache file, holes
// included, and Release announced the whole size; the owner then adopted
// zeros for every chunk the reader never fetched. Now the chunks a write
// touches are fetched first, a copy with chunks still missing stays a cache
// copy, and Release defers the announce to the fill.

